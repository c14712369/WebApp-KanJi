export const ICON_GROUPS = GROUPS.map(([id, label, icons]) => ({
  id,
  label,
  icons: icons.map(([name, iconLabelText, keywords]) => ({ name, label: iconLabelText, keywords })),
}));

export const ALL_ICON_NAMES = ICON_GROUPS.flatMap(g => g.icons.map(i => i.name));

const LABELS = new Map(ICON_GROUPS.flatMap(g => g.icons.map(i => [i.name, i.label])));

/** 圖示的中文名稱（無障礙標籤、提示用）；不認識的名稱原樣回傳 */
export const iconLabel = (name) => LABELS.get(name) || name;

/**
 * 搜尋：比對分組名稱（整組列出）、圖示中文名稱、關鍵字、英文名稱；不分大小寫。
 * 空白查詢 → 全部分組；沒有結果的分組不列出。
 */
export function searchIconGroups(query) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return ICON_GROUPS;
  const out = [];
  for (const g of ICON_GROUPS) {
    if (g.label.toLowerCase().includes(q)) { out.push(g); continue; }
    const icons = g.icons.filter(i =>
      i.label.toLowerCase().includes(q)
      || i.keywords.toLowerCase().includes(q)
      || i.name.toLowerCase().includes(q));
    if (icons.length) out.push({ ...g, icons });
  }
  return out;
}
